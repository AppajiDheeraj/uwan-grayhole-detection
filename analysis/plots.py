def pooled(case, value):
    """Mean over every live run of a case (all grayhole counts and loads) and its 95% t-interval over topologies."""
    per_seed = [np.mean([value(by_case[(*g, case, s)]) for g in SET]) for s in seeds]
    return mean_ci(per_seed)


