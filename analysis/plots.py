def paired(g, case, value):
    """Mean of `value` and the 95% CI of its difference from 'attack, no defence' on the same topology."""
    rs = [by_case[(*g, case, s)] for s in seeds]
    base = [by_case[(*g, "nodefense", s)] for s in seeds]
    mean = np.mean([value(r) for r in rs])
    return mean, (0.0 if case == "nodefense" else mean_ci([value(a) - value(b) for a, b in zip(rs, base)])[1])


