def table(title, header, rows):
    summary.extend([f"### {title}", "", "| " + " | ".join(header) + " |", "|" + "---|" * len(header)])
    summary.extend("| " + " | ".join(str(c) for c in row) + " |" for row in rows)
    summary.append("")


def save(fig, name, caption):
    fig.tight_layout()
    fig.savefig(FIGS / f"{name}.png", bbox_inches="tight")
    plt.close(fig)
    summary.extend([f"**{name}.** {caption}", ""])


