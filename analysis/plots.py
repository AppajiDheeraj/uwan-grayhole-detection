def mean_ci(xs):
    """Mean and 95% t-interval half-width."""
    a = np.array(xs, dtype=float)
    if len(a) < 2:
        return (a.mean() if len(a) else float("nan")), 0.0
    return a.mean(), T975.get(len(a) - 1, 1.96) * a.std(ddof=1) / math.sqrt(len(a))


def per_topology(rows, value):
    """One number per topology (seed): the mean of `value` over that topology's rows."""
    by_seed = defaultdict(list)
    for r in rows:
        by_seed[r["seed"]].append(value(r))
    return [sum(v) / len(v) for v in by_seed.values()]


