def rate(rule, method, scenario, num, den):
    rs = [r for r in compare if r["rule"] == rule and r["method"] == method and r["scenario"] == scenario]
    d = sum(float(r[den]) for r in rs)
    return 100 * sum(float(r[num]) for r in rs) / d if d else float("nan")


